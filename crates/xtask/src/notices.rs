//! Generates the THIRD-PARTY-NOTICES.md files.

use std::{
    collections::HashSet,
    fs,
    path::{
        Path,
        PathBuf,
    },
};

use anyhow::{
    Context,
    Result,
    anyhow,
    bail,
};

use crate::{
    Tools,
    read_text,
};

/// The crates that ship a binary, and what ships, for the title of their notices.
const TARGETS: [(&str, &str); 4] = [
    ("pzmap-tools", "The pack-view program"),
    ("pzmap2img", "The pzmap2img program"),
    ("pzmap-java", "The native library inside the pzmap jar"),
    ("pzmap-python", "The native module inside the pzmap wheel"),
];

/// The line at the top of every generated file.
const GENERATED_NOTE: &str = "This file is generated by `cargo run -p xtask -- notices`. Run it to update this file; do not edit it by hand.";

/// Writes the THIRD-PARTY-NOTICES.md file of each crate that ships a binary, or with `check`,
/// fails if any of them no longer covers what the binary contains.
///
/// The check passes when a file lists other versions of the same crates, or crates the binary no
/// longer uses. Those differences are harmless, and `release prepare` regenerates the files for
/// every release, so each release ships exact notices. A dependency update such as a Dependabot
/// pull request then only fails the check when it adds a crate or changes a license.
///
/// cargo-about lists the Rust crates, using about.toml and about.hbs at the repository root.
/// This task adds a title and the notices cargo-about cannot see: libwebp, which libwebp-sys
/// compiles from C sources, and the Fira Code font that pack-view embeds.
pub(crate) fn notices(check: bool) -> Result<()> {
    let tools = Tools::new()?;
    tools.require_cargo_about()?;

    let metadata = tools.metadata()?;
    let work = metadata.target_directory.join("xtask").join("notices");
    fs::create_dir_all(&work).with_context(|| format!("cannot create {}", work.display()))?;

    // A Windows checkout may give the template CRLF line endings, which cargo-about would copy
    // into its output. A copy with LF endings keeps the output the same on every platform.
    let template = work.join("about.hbs");
    let text = read_text(&tools.root.join("about.hbs"))?;
    fs::write(&template, text).with_context(|| format!("cannot write {}", template.display()))?;

    let mut stale = Vec::new();
    for (krate, artifact) in TARGETS {
        let generated = tools.generate(krate, artifact, &template, &work, &metadata)?;
        let relative = format!("crates/{krate}/THIRD-PARTY-NOTICES.md");
        let file = tools.root.join(&relative);
        if check {
            let current = normalize(&fs::read(&file).unwrap_or_default());
            let generated = normalize(&generated);
            let missing = missing_lines(&current, &generated);
            if !missing.is_empty() {
                stale.push((relative, missing));
            } else if current != generated {
                println!(
                    "{relative} lists other crate versions or unused crates, which is fine until \
                     the next release regenerates it"
                );
            }
        } else {
            fs::write(&file, &generated)
                .with_context(|| format!("cannot write {}", file.display()))?;
            println!("wrote {relative}");
        }
    }

    if !stale.is_empty() {
        for (file, missing) in &stale {
            eprintln!("{file} lacks these lines, with versions shown as <version>:");
            for (section, line) in missing.iter().take(10) {
                eprintln!("  in {section}: {line}");
            }
            if missing.len() > 10 {
                eprintln!("  and {} more", missing.len() - 10);
            }
        }
        bail!("run `cargo run -p xtask -- notices` to update the notices");
    }
    Ok(())
}

/// What this task needs from `cargo metadata`.
struct Metadata {
    target_directory: PathBuf,
    /// The directory of the libwebp-sys sources, if the workspace depends on it.
    libwebp_sys: Option<PathBuf>,
}

impl Tools {
    fn require_cargo_about(&self) -> Result<()> {
        let found = self
            .cargo()
            .args(["about", "--version"])
            .output()
            .is_ok_and(|output| output.status.success());
        if !found {
            bail!("cargo-about is not installed; install it with `cargo install cargo-about`");
        }
        Ok(())
    }

    fn metadata(&self) -> Result<Metadata> {
        let output = self
            .cargo()
            .args(["metadata", "--format-version", "1", "--locked"])
            .output()
            .context("cannot run cargo metadata")?;
        if !output.status.success() {
            bail!(
                "cargo metadata failed:\n{}",
                String::from_utf8_lossy(&output.stderr)
            );
        }
        let json: serde_json::Value =
            serde_json::from_slice(&output.stdout).context("cannot parse cargo metadata")?;

        let target_directory = json
            .get("target_directory")
            .and_then(serde_json::Value::as_str)
            .map(PathBuf::from)
            .ok_or_else(|| anyhow!("cargo metadata has no target_directory"))?;
        let libwebp_sys = json
            .get("packages")
            .and_then(serde_json::Value::as_array)
            .ok_or_else(|| anyhow!("cargo metadata has no packages"))?
            .iter()
            .find(|package| {
                package.get("name").and_then(serde_json::Value::as_str) == Some("libwebp-sys")
            })
            .and_then(|package| package.get("manifest_path"))
            .and_then(serde_json::Value::as_str)
            .and_then(|path| Path::new(path).parent())
            .map(Path::to_path_buf);
        Ok(Metadata {
            target_directory,
            libwebp_sys,
        })
    }

    /// Returns true if `krate`, built with its default features, links `dependency` on any
    /// platform.
    fn links(&self, krate: &str, dependency: &str) -> Result<bool> {
        let output = self
            .cargo()
            .args(["tree", "--locked", "--target", "all", "-e", "normal"])
            .args(["-p", krate, "-i", dependency])
            .output()
            .context("cannot run cargo tree")?;
        Ok(output.status.success())
    }

    /// Returns the notices for `krate`. `artifact` names what ships, for the title.
    fn generate(
        &self,
        krate: &str,
        artifact: &str,
        template: &Path,
        work: &Path,
        metadata: &Metadata,
    ) -> Result<Vec<u8>> {
        let body_path = work.join(format!("{krate}.body.md"));
        let manifest = self.root.join("crates").join(krate).join("Cargo.toml");
        // cargo-about warns about clarifications for crates outside this crate's tree, which
        // is expected, so its messages are only shown when it fails.
        let output = self
            .cargo()
            .args(["about", "generate", "--locked", "--fail", "--manifest-path"])
            .arg(&manifest)
            .arg("--output-file")
            .arg(&body_path)
            .arg(template)
            .output()
            .context("cannot run cargo about")?;
        if !output.status.success() {
            bail!(
                "cargo-about failed for {krate}:\n{}{}",
                String::from_utf8_lossy(&output.stdout),
                String::from_utf8_lossy(&output.stderr)
            );
        }
        let body =
            fs::read(&body_path).with_context(|| format!("cannot read {}", body_path.display()))?;

        let mut out = format!(
            "{GENERATED_NOTE}\n\n# Third-party notices\n\n{artifact} contains code from the \
             projects below.\nEach section gives a license's text and the components that use \
             it.\n\n"
        )
        .into_bytes();
        out.extend_from_slice(&body);
        if self.links(krate, "libwebp-sys")? {
            let dir = metadata
                .libwebp_sys
                .as_deref()
                .ok_or_else(|| anyhow!("cargo metadata does not list libwebp-sys"))?;
            out.extend_from_slice(libwebp_notice(&dir.join("vendor"))?.as_bytes());
        }
        if krate == "pzmap-tools" {
            out.extend_from_slice(fira_code_notice(&self.root, &body)?.as_bytes());
        }

        // Drop blank lines at the end, keeping one line break.
        while out.last() == Some(&b'\n') {
            out.pop();
        }
        out.push(b'\n');
        Ok(out)
    }
}

/// The notice for libwebp, whose sources libwebp-sys keeps in `vendor`.
fn libwebp_notice(vendor: &Path) -> Result<String> {
    // These files come from the Cargo registry, not from a checkout, so they are read as they
    // are.
    let header = read_registry(&vendor.join("src/dec/vp8i_dec.h"))?;
    let mut parts = Vec::new();
    for line in header.lines() {
        let Some(rest) = line.strip_prefix("#define DEC_") else {
            continue;
        };
        for part in ["MAJ", "MIN", "REV"] {
            let Some(value) = rest
                .strip_prefix(part)
                .and_then(|rest| rest.strip_prefix("_VERSION "))
            else {
                continue;
            };
            let digits: String = value.chars().take_while(char::is_ascii_digit).collect();
            if !digits.is_empty() {
                parts.push(digits);
            }
        }
    }
    if parts.len() != 3 {
        bail!("cannot find the libwebp version in {}", vendor.display());
    }
    let version = parts.join(".");
    let copying = read_registry(&vendor.join("COPYING"))?;
    let patents = read_registry(&vendor.join("PATENTS"))?;
    Ok(format!(
        "## libwebp

The libwebp-sys crate compiles libwebp {version} from C sources it ships, so the binary contains
libwebp. libwebp is licensed under the BSD 3-Clause License, with an additional patent grant.

```text
{}
```

```text
{}
```
",
        copying.trim_end_matches('\n'),
        patents.trim_end_matches('\n'),
    ))
}

/// The notice for Fira Code. cargo-about finds the font's license in the pzmap-tools package
/// and gives it a section of its own, so this section points there instead of repeating it.
/// `body` is cargo-about's output.
fn fira_code_notice(root: &Path, body: &[u8]) -> Result<String> {
    let ofl = "crates/pzmap-tools/assets/fonts/OFL.txt";
    let text = read_text(&root.join(ofl))?;
    let first_line = text.lines().next().unwrap_or_default();
    let body = String::from_utf8_lossy(body);
    if !body.contains(first_line) {
        bail!("the pzmap-tools notices lack the Fira Code license from {ofl}");
    }
    Ok(String::from(
        "## Fira Code

pack-view embeds the Fira Code font to draw its window. Fira Code is licensed under the SIL
Open Font License 1.1, whose text is in the section of that name above. The pzmap-tools source
package also holds it at `assets/fonts/OFL.txt`.
",
    ))
}

/// Reads a text file from the Cargo registry.
fn read_registry(path: &Path) -> Result<String> {
    fs::read_to_string(path).with_context(|| format!("cannot read {}", path.display()))
}

/// The lines of `generated` that `current` lacks, each with the heading of its section.
///
/// Versions and crate counts are masked first. A line counts as present only under the same
/// heading, so a crate that moves to another license's section is reported.
fn missing_lines(current: &[u8], generated: &[u8]) -> Vec<(String, String)> {
    let present: HashSet<(String, String)> = keyed_lines(current).into_iter().collect();
    keyed_lines(generated)
        .into_iter()
        .filter(|line| !present.contains(line))
        .collect()
}

/// The non-blank lines of a notices file, with versions and crate counts masked, each paired
/// with the heading of the section it is in. Lines inside code blocks, which hold the license
/// texts, are never taken as headings.
fn keyed_lines(text: &[u8]) -> Vec<(String, String)> {
    let text = String::from_utf8_lossy(&mask_versions(text)).into_owned();
    let mut section = String::new();
    let mut in_code = false;
    let mut lines = Vec::new();
    for line in text.lines() {
        if line.starts_with("```") {
            in_code = !in_code;
        } else if !in_code && line.starts_with('#') {
            section = line.to_owned();
            continue;
        }
        if !line.trim().is_empty() {
            lines.push((section.clone(), mask_count(line)));
        }
    }
    lines
}

/// Masks the number in a summary line such as `- MIT License (MIT): 95 crates`, which changes
/// whenever a crate is added or removed.
fn mask_count(line: &str) -> String {
    let counted = line.starts_with("- ")
        && (line.ends_with(" crates") || line.ends_with(" crate"))
        && line.contains(": ");
    match line.rsplit_once(": ") {
        Some((name, _)) if counted => format!("{name}: <count> crates"),
        _ => line.to_owned(),
    }
}

/// Replaces each version number such as `1.1.4` or `0.2.0-rc.1` with `<version>`.
///
/// A version starts after a space or at the start of the text, has three numbers separated by
/// dots, and may have a pre-release or build suffix. Only crate versions and the libwebp version
/// look like that in a notices file. A version-like number inside a license text is the same in
/// both files, so masking it changes nothing.
fn mask_versions(text: &[u8]) -> Vec<u8> {
    let mut out = Vec::with_capacity(text.len());
    let mut at = 0;
    while let Some(&byte) = text.get(at) {
        let starts_word = at == 0 || text.get(at - 1) == Some(&b' ');
        match (starts_word && byte.is_ascii_digit())
            .then(|| version_len(text.get(at..).unwrap_or_default()))
            .flatten()
        {
            Some(len) => {
                out.extend_from_slice(b"<version>");
                at += len;
            }
            None => {
                out.push(byte);
                at += 1;
            }
        }
    }
    out
}

/// The length of the version at the start of `text`, if one ends there in a space, punctuation
/// or the end of the text.
fn version_len(text: &[u8]) -> Option<usize> {
    let mut at = 0;
    for part in 0..3 {
        if part > 0 {
            if text.get(at) != Some(&b'.') {
                return None;
            }
            at += 1;
        }
        let digits = text
            .get(at..)?
            .iter()
            .take_while(|byte| byte.is_ascii_digit())
            .count();
        if digits == 0 {
            return None;
        }
        at += digits;
    }
    if matches!(text.get(at), Some(b'-' | b'+')) {
        at += 1;
        at += text
            .get(at..)?
            .iter()
            .take_while(|byte| byte.is_ascii_alphanumeric() || matches!(byte, b'.' | b'-' | b'+'))
            .count();
    }
    match text.get(at) {
        None | Some(b' ' | b')' | b',' | b'.' | b':' | b';' | b'\n' | b'\r') => Some(at),
        Some(_) => None,
    }
}

/// Drops the carriage returns before each line break, so a Windows checkout compares equal to a
/// Linux one. Some license texts already end their lines with CRLF, and a checkout may add
/// another carriage return to them.
fn normalize(bytes: &[u8]) -> Vec<u8> {
    let mut out = Vec::with_capacity(bytes.len());
    for &byte in bytes {
        if byte == b'\n' {
            while out.last() == Some(&b'\r') {
                out.pop();
            }
        }
        out.push(byte);
    }
    out
}

#[cfg(test)]
#[allow(clippy::unwrap_used, clippy::indexing_slicing)]
mod tests {
    use super::{
        mask_versions,
        missing_lines,
        normalize,
    };

    #[test]
    fn mask_versions_hides_only_versions() {
        let mask = |text: &str| String::from_utf8(mask_versions(text.as_bytes())).unwrap();
        assert_eq!(
            mask("- rustix 1.1.4 (https://github.com/bytecodealliance/rustix)\n"),
            "- rustix <version> (https://github.com/bytecodealliance/rustix)\n"
        );
        assert_eq!(
            mask("compiles libwebp 1.6.0 from"),
            "compiles libwebp <version> from"
        );
        assert_eq!(mask("- a 0.2.0-rc.1 (x)"), "- a <version> (x)");
        assert_eq!(mask("1.2.3"), "<version>");
        // Not versions: two numbers, digits inside a word, or a version glued to text.
        for unchanged in [
            "Version 2.0, January",
            "sha256 abc1.2.3",
            "- a 1.2.3x (y)",
            "MIT: 95",
        ] {
            assert_eq!(mask(unchanged), unchanged);
        }
    }

    const NOTICES: &str = "## Licenses

- MIT License (MIT): 2 crates
- Apache License 2.0 (Apache-2.0): 1 crate

## MIT License

```text
# Not a heading
MIT text
```

Used by:

- rustix 1.1.4 (https://example.com/rustix)
- windows-sys 0.59.0 (https://example.com/windows)

## Apache License 2.0

```text
Apache text
```

Used by:

- serde 1.0.0 (https://example.com/serde)
";

    /// The lines that the committed `NOTICES` lack, compared with `generated`.
    fn missing(generated: &str) -> Vec<String> {
        missing_lines(NOTICES.as_bytes(), generated.as_bytes())
            .into_iter()
            .map(|(_, line)| line)
            .collect()
    }

    #[test]
    fn a_version_bump_or_a_removed_crate_is_covered() {
        let bumped = NOTICES
            .replace("rustix 1.1.4", "rustix 1.1.5")
            .replace("- windows-sys 0.59.0 (https://example.com/windows)\n", "")
            .replace("(MIT): 2 crates", "(MIT): 1 crate");
        assert!(missing(&bumped).is_empty());
    }

    #[test]
    fn a_new_crate_or_license_text_is_missing() {
        let added = NOTICES.replace(
            "- rustix 1.1.4 (https://example.com/rustix)\n",
            "- rustix 1.1.4 (https://example.com/rustix)\n- libc 0.2.0 (https://example.com/libc)\n",
        );
        assert_eq!(
            missing(&added),
            ["- libc <version> (https://example.com/libc)"]
        );
        assert_eq!(
            missing(&NOTICES.replace("MIT text", "MIT text, changed")),
            ["MIT text, changed"]
        );
    }

    #[test]
    fn a_crate_that_changes_license_is_missing() {
        // serde moves from the Apache section to the MIT one.
        let moved = NOTICES
            .replace("- serde 1.0.0 (https://example.com/serde)\n", "")
            .replace(
                "- windows-sys 0.59.0 (https://example.com/windows)\n",
                "- windows-sys 0.59.0 (https://example.com/windows)\n- serde 1.0.0 \
                 (https://example.com/serde)\n",
            );
        assert_eq!(
            missing(&moved),
            ["- serde <version> (https://example.com/serde)"]
        );
    }

    #[test]
    fn normalize_drops_carriage_returns_before_line_breaks() {
        assert_eq!(normalize(b"a\r\nb\r\r\nc\rd\n"), b"a\nb\nc\rd\n");
    }
}
