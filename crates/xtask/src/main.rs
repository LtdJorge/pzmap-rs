//! Maintenance tasks for the workspace, written in Rust so they run the same on every platform.
//!
//! ```text
//! cargo run -p xtask -- notices           regenerate the THIRD-PARTY-NOTICES.md files
//! cargo run -p xtask -- notices --check   fail if any of them is out of date
//! ```

use std::{
    env,
    ffi::OsString,
    fs,
    path::{
        Path,
        PathBuf,
    },
    process::{
        Command,
        ExitCode,
    },
};

use anyhow::{
    Context,
    Result,
    anyhow,
    bail,
};

const USAGE: &str = "usage: cargo run -p xtask -- notices [--check]";

fn main() -> ExitCode {
    let args: Vec<String> = env::args().skip(1).collect();
    let check = match args
        .iter()
        .map(String::as_str)
        .collect::<Vec<_>>()
        .as_slice()
    {
        ["notices"] => false,
        ["notices", "--check"] => true,
        _ => {
            eprintln!("{USAGE}");
            return ExitCode::from(2);
        }
    };
    match notices(check) {
        Ok(()) => ExitCode::SUCCESS,
        Err(error) => {
            eprintln!("error: {error:#}");
            ExitCode::FAILURE
        }
    }
}

/// The crates that ship a binary, and what ships, for the title of their notices.
const TARGETS: [(&str, &str); 4] = [
    ("pzmap-tools", "The pack-view program"),
    ("pzmap2img", "The pzmap2img program"),
    ("pzmap-java", "The native library inside the pzmap jar"),
    ("pzmap-python", "The native module inside the pzmap wheel"),
];

/// The line at the top of every generated file.
const GENERATED_NOTE: &str = "This file is generated by `cargo run -p xtask -- notices`. Run it to update this file; do not edit it by hand.";

/// Writes the THIRD-PARTY-NOTICES.md file of each crate that ships a binary, or with `check`,
/// fails if any of them is out of date.
///
/// cargo-about lists the Rust crates, using about.toml and about.hbs at the repository root.
/// This task adds a title and the notices cargo-about cannot see: libwebp, which libwebp-sys
/// compiles from C sources, and the Fira Code font that pack-view embeds.
fn notices(check: bool) -> Result<()> {
    let tools = Tools::new()?;
    tools.require_cargo_about()?;

    let metadata = tools.metadata()?;
    let work = metadata.target_directory.join("xtask").join("notices");
    fs::create_dir_all(&work).with_context(|| format!("cannot create {}", work.display()))?;

    // A Windows checkout may give the template CRLF line endings, which cargo-about would copy
    // into its output. A copy with LF endings keeps the output the same on every platform.
    let template = work.join("about.hbs");
    let text = read_text(&tools.root.join("about.hbs"))?;
    fs::write(&template, text).with_context(|| format!("cannot write {}", template.display()))?;

    let mut stale = Vec::new();
    for (krate, artifact) in TARGETS {
        let generated = tools.generate(krate, artifact, &template, &work, &metadata)?;
        let relative = format!("crates/{krate}/THIRD-PARTY-NOTICES.md");
        let file = tools.root.join(&relative);
        if check {
            let current = fs::read(&file).unwrap_or_default();
            if normalize(&current) != normalize(&generated) {
                stale.push(relative);
            }
        } else {
            fs::write(&file, &generated)
                .with_context(|| format!("cannot write {}", file.display()))?;
            println!("wrote {relative}");
        }
    }

    if !stale.is_empty() {
        for file in &stale {
            eprintln!("{file} is out of date");
        }
        bail!("run `cargo run -p xtask -- notices` to update the notices");
    }
    Ok(())
}

/// The cargo program and the workspace root that its commands run in.
struct Tools {
    cargo: OsString,
    root: PathBuf,
}

/// What this task needs from `cargo metadata`.
struct Metadata {
    target_directory: PathBuf,
    /// The directory of the libwebp-sys sources, if the workspace depends on it.
    libwebp_sys: Option<PathBuf>,
}

impl Tools {
    fn new() -> Result<Self> {
        // `cargo run` tells the program which cargo started it.
        let cargo = env::var_os("CARGO").unwrap_or_else(|| "cargo".into());
        let root = Path::new(env!("CARGO_MANIFEST_DIR"))
            .ancestors()
            .nth(2)
            .ok_or_else(|| anyhow!("cannot find the workspace root"))?
            .to_path_buf();
        Ok(Self { cargo, root })
    }

    fn cargo(&self) -> Command {
        let mut command = Command::new(&self.cargo);
        command.current_dir(&self.root);
        command
    }

    fn require_cargo_about(&self) -> Result<()> {
        let found = self
            .cargo()
            .args(["about", "--version"])
            .output()
            .is_ok_and(|output| output.status.success());
        if !found {
            bail!("cargo-about is not installed; install it with `cargo install cargo-about`");
        }
        Ok(())
    }

    fn metadata(&self) -> Result<Metadata> {
        let output = self
            .cargo()
            .args(["metadata", "--format-version", "1", "--locked"])
            .output()
            .context("cannot run cargo metadata")?;
        if !output.status.success() {
            bail!(
                "cargo metadata failed:\n{}",
                String::from_utf8_lossy(&output.stderr)
            );
        }
        let json: serde_json::Value =
            serde_json::from_slice(&output.stdout).context("cannot parse cargo metadata")?;

        let target_directory = json
            .get("target_directory")
            .and_then(serde_json::Value::as_str)
            .map(PathBuf::from)
            .ok_or_else(|| anyhow!("cargo metadata has no target_directory"))?;
        let libwebp_sys = json
            .get("packages")
            .and_then(serde_json::Value::as_array)
            .ok_or_else(|| anyhow!("cargo metadata has no packages"))?
            .iter()
            .find(|package| {
                package.get("name").and_then(serde_json::Value::as_str) == Some("libwebp-sys")
            })
            .and_then(|package| package.get("manifest_path"))
            .and_then(serde_json::Value::as_str)
            .and_then(|path| Path::new(path).parent())
            .map(Path::to_path_buf);
        Ok(Metadata {
            target_directory,
            libwebp_sys,
        })
    }

    /// Returns true if `krate`, built with its default features, links `dependency` on any
    /// platform.
    fn links(&self, krate: &str, dependency: &str) -> Result<bool> {
        let output = self
            .cargo()
            .args(["tree", "--locked", "--target", "all", "-e", "normal"])
            .args(["-p", krate, "-i", dependency])
            .output()
            .context("cannot run cargo tree")?;
        Ok(output.status.success())
    }

    /// Returns the notices for `krate`. `artifact` names what ships, for the title.
    fn generate(
        &self,
        krate: &str,
        artifact: &str,
        template: &Path,
        work: &Path,
        metadata: &Metadata,
    ) -> Result<Vec<u8>> {
        let body_path = work.join(format!("{krate}.body.md"));
        let manifest = self.root.join("crates").join(krate).join("Cargo.toml");
        // cargo-about warns about clarifications for crates outside this crate's tree, which
        // is expected, so its messages are only shown when it fails.
        let output = self
            .cargo()
            .args(["about", "generate", "--locked", "--fail", "--manifest-path"])
            .arg(&manifest)
            .arg("--output-file")
            .arg(&body_path)
            .arg(template)
            .output()
            .context("cannot run cargo about")?;
        if !output.status.success() {
            bail!(
                "cargo-about failed for {krate}:\n{}{}",
                String::from_utf8_lossy(&output.stdout),
                String::from_utf8_lossy(&output.stderr)
            );
        }
        let body =
            fs::read(&body_path).with_context(|| format!("cannot read {}", body_path.display()))?;

        let mut out = format!(
            "{GENERATED_NOTE}\n\n# Third-party notices\n\n{artifact} contains code from the \
             projects below.\nEach section gives a license's text and the components that use \
             it.\n\n"
        )
        .into_bytes();
        out.extend_from_slice(&body);
        if self.links(krate, "libwebp-sys")? {
            let dir = metadata
                .libwebp_sys
                .as_deref()
                .ok_or_else(|| anyhow!("cargo metadata does not list libwebp-sys"))?;
            out.extend_from_slice(libwebp_notice(&dir.join("vendor"))?.as_bytes());
        }
        if krate == "pzmap-tools" {
            out.extend_from_slice(fira_code_notice(&self.root, &body)?.as_bytes());
        }

        // Drop blank lines at the end, keeping one line break.
        while out.last() == Some(&b'\n') {
            out.pop();
        }
        out.push(b'\n');
        Ok(out)
    }
}

/// The notice for libwebp, whose sources libwebp-sys keeps in `vendor`.
fn libwebp_notice(vendor: &Path) -> Result<String> {
    // These files come from the Cargo registry, not from a checkout, so they are read as they
    // are.
    let header = read_registry(&vendor.join("src/dec/vp8i_dec.h"))?;
    let mut parts = Vec::new();
    for line in header.lines() {
        let Some(rest) = line.strip_prefix("#define DEC_") else {
            continue;
        };
        for part in ["MAJ", "MIN", "REV"] {
            let Some(value) = rest
                .strip_prefix(part)
                .and_then(|rest| rest.strip_prefix("_VERSION "))
            else {
                continue;
            };
            let digits: String = value.chars().take_while(char::is_ascii_digit).collect();
            if !digits.is_empty() {
                parts.push(digits);
            }
        }
    }
    if parts.len() != 3 {
        bail!("cannot find the libwebp version in {}", vendor.display());
    }
    let version = parts.join(".");
    let copying = read_registry(&vendor.join("COPYING"))?;
    let patents = read_registry(&vendor.join("PATENTS"))?;
    Ok(format!(
        "## libwebp

The libwebp-sys crate compiles libwebp {version} from C sources it ships, so the binary contains
libwebp. libwebp is licensed under the BSD 3-Clause License, with an additional patent grant.

```text
{}
```

```text
{}
```
",
        copying.trim_end_matches('\n'),
        patents.trim_end_matches('\n'),
    ))
}

/// The notice for Fira Code. cargo-about finds the font's license in the pzmap-tools package
/// and gives it a section of its own, so this section points there instead of repeating it.
/// `body` is cargo-about's output.
fn fira_code_notice(root: &Path, body: &[u8]) -> Result<String> {
    let ofl = "crates/pzmap-tools/assets/fonts/OFL.txt";
    let text = read_text(&root.join(ofl))?;
    let first_line = text.lines().next().unwrap_or_default();
    let body = String::from_utf8_lossy(body);
    if !body.contains(first_line) {
        bail!("the pzmap-tools notices lack the Fira Code license from {ofl}");
    }
    Ok(String::from(
        "## Fira Code

pack-view embeds the Fira Code font to draw its window. Fira Code is licensed under the SIL
Open Font License 1.1, whose text is in the section of that name above. The pzmap-tools source
package also holds it at `assets/fonts/OFL.txt`.
",
    ))
}

/// Reads a text file with LF line endings, whatever the checkout gave it.
fn read_text(path: &Path) -> Result<String> {
    let text =
        fs::read_to_string(path).with_context(|| format!("cannot read {}", path.display()))?;
    Ok(text.replace("\r\n", "\n"))
}

/// Reads a text file from the Cargo registry.
fn read_registry(path: &Path) -> Result<String> {
    fs::read_to_string(path).with_context(|| format!("cannot read {}", path.display()))
}

/// Drops the carriage returns before each line break, so a Windows checkout compares equal to a
/// Linux one. Some license texts already end their lines with CRLF, and a checkout may add
/// another carriage return to them.
fn normalize(bytes: &[u8]) -> Vec<u8> {
    let mut out = Vec::with_capacity(bytes.len());
    for &byte in bytes {
        if byte == b'\n' {
            while out.last() == Some(&b'\r') {
                out.pop();
            }
        }
        out.push(byte);
    }
    out
}

#[cfg(test)]
mod tests {
    use super::normalize;

    #[test]
    fn normalize_drops_carriage_returns_before_line_breaks() {
        assert_eq!(normalize(b"a\r\nb\r\r\nc\rd\n"), b"a\nb\nc\rd\n");
    }
}
